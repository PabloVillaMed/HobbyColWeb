  const LOCALES = { es: 'es-ES', en: 'en-GB' };

  let current = 'es';

  function setLang(lang) {
    current = STRINGS[lang] ? lang : 'es';
    return current;
  }
  function getLang() {
    return current;
  }
  function locale() {
    return LOCALES[current];
  }
  /* t('key') for plain strings, t('key', arg) for the function-valued ones. */
  function t(key, arg) {
    const table = STRINGS[current] || STRINGS.es;
    let value = key in table ? table[key] : STRINGS.es[key];
    if (value === undefined) value = key;
    return typeof value === 'function' ? value(arg) : value;
  }

  global.I18N = { t, setLang, getLang, locale, STRINGS };
